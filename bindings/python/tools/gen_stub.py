"""Writes, or checks, the type stub python/civkit/__init__.pyi from the installed calculations (ADR 0014 Q-E).

    python tools/gen_stub.py           # write the stub
    python tools/gen_stub.py --check   # exit 1 if the stub differs from what the calculations give

The typed functions are generated at import, so editors and type checkers learn their signatures from this stub.
CI runs the check (tests/test_stub.py), so the stub cannot drift from the descriptors.
"""

from __future__ import annotations

import sys
from pathlib import Path

STUB = Path(__file__).resolve().parents[1] / "python" / "civkit" / "__init__.pyi"

HEADER = '''\
# Generated by bindings/python/tools/gen_stub.py from the calculation descriptors. Do not edit by hand:
# run `python tools/gen_stub.py` after adding or changing a calculation.
import builtins
import os
from typing import Any, Literal, Mapping, Sequence

__version__: str

Input = Q | float | int | str | tuple[Any, str] | Sequence[Q] | Sequence[float] | Mapping[str, Any]

class Q:
    value: Any
    unit: str | None
    negative: bool | None
    def __init__(self, value: Any, unit: str | None = None, negative: bool | None = None) -> None: ...
    def to(self, unit: str) -> Q: ...
    def to_json(self) -> dict[str, Any]: ...
    def __float__(self) -> float: ...

class Result:
    id: str
    version: int
    civkit_version: str
    outputs: dict[str, Q | builtins.list[Q]]
    trace: builtins.list[dict[str, Any]]
    warnings: builtins.list[dict[str, Any]]
    references: builtins.list[str]
    assumptions: builtins.list[str]
    request: dict[str, Any]
    def __init__(self, response: dict[str, Any], request: dict[str, Any], rerun: Any) -> None: ...
    def to_dict(self) -> dict[str, Any]: ...

class CivKitError(Exception):
    code: str
    message: str
    input: str | None
    index: int | None
    errors: builtins.list[dict[str, Any]]
    def __init__(self, errors: builtins.list[dict[str, Any]]) -> None: ...
    @classmethod
    def from_envelope(cls, envelope: dict[str, Any]) -> CivKitError: ...

def call(
    id: str, /, *, version: int | None = None, output_units: Mapping[str, str] | None = None, **inputs: Any
) -> Result: ...
def list() -> builtins.list[dict[str, Any]]: ...
def describe(id: str, version: int | None = None) -> dict[str, Any]: ...
def version() -> str: ...

Source = str | os.PathLike[str] | bytes | bytearray | memoryview

class _drawing:
    @staticmethod
    def analyze(source: Source, *, detail: Literal['layer', 'entity'] = 'layer') -> dict[str, Any]:
        """The drawing report (drawing.analyze, D-28) of a DXF path or bytes."""
    @staticmethod
    def schedule_csv(source: Source) -> str:
        """The quantity schedule (CSV text) of a DXF path or bytes."""

drawing: _drawing
'''


def _class_name(path: list[str]) -> str:
    return "_" + "_".join(path)


def _param(spec: dict) -> str:
    if spec.get("kind") == "choice":
        kind = "Literal[" + ", ".join(repr(c) for c in spec["choices"]) + "]"
    else:
        kind = "Input"
    return f"{spec['name']}: {kind}" + ("" if spec["required"] else " | None = None")


def render(descriptors: list[dict]) -> str:
    """The stub text for these descriptors."""
    from civkit._typed import condition  # the same rule as the typed functions' docstrings

    tree: dict = {}
    for d in sorted(descriptors, key=lambda d: d["id"]):
        *path, method = d["id"].split(".")
        node = tree
        for part in path:
            node = node.setdefault(part, {})
        node[method] = d

    out = [HEADER]

    def emit(path: list[str], node: dict) -> None:
        for name, child in node.items():
            if "id" not in child:
                emit(path + [name], child)
        out.append(f"\nclass {_class_name(path)}:")
        for name, child in node.items():
            if "id" in child:
                params = ", ".join([_param(i) for i in child["inputs"]] + ["output_units: Mapping[str, str] | None = None"])
                out.append("    @staticmethod")
                out.append(f"    def {name}(*, {params}) -> Result:")
                doc = f'{child["title"]} ({child["id"]}, version {child["version"]}).'
                conditional = [(i["name"], condition(i)) for i in child["inputs"] if condition(i)]
                if conditional:
                    doc += "\n\n        Conditional requirements:\n" + "\n".join(
                        f"        - {n} is required when {c}" for n, c in conditional
                    ) + "\n        "
                out.append(f'        """{doc}"""')
            else:
                out.append(f"    {name}: {_class_name(path + [name])}")

    for root, node in tree.items():
        emit([root], node)
    out.append("")
    for root in tree:
        out.append(f"{root}: {_class_name([root])}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    import civkit

    text = render(civkit.list())
    if "--check" in argv:
        current = STUB.read_text(encoding="utf-8") if STUB.exists() else ""
        if current != text:
            print(f"{STUB} is out of date: run `python tools/gen_stub.py`", file=sys.stderr)
            return 1
        return 0
    STUB.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {STUB}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
