# Provenance: Claude Sonnet 5.5 (claude-sonnet-5-5) · first drafted 2026-11-27 11:21 IST · last edited 2026-11-27 11:21 IST
"""Generates the calculation pages in docs/calculations/ from the installed calculations (ENGINEERING_STANDARDS §2
item 7: formula, symbols, references, assumptions, limits, example).

    python tools/gen_calc_docs.py           # write the pages
    python tools/gen_calc_docs.py --check   # exit 1 if a page differs from what the calculations give

Everything comes from the engine through the Python package: the descriptor, the calculation's reference case (its
`examples`), and the trace of that case for the method. Numbers shown are rounded to 6 significant figures, so the
pages do not depend on last-bit differences between platforms. CI runs the check
(bindings/python/tests/test_docs.py).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "calculations"

DISCLAIMER = "CivKit results support, and do not replace, the judgement of a qualified engineer."
GENERATED = "Generated by `tools/gen_calc_docs.py` from the calculation's descriptor and reference case. Do not edit by hand."


def number(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, list):
        return "[" + ", ".join(number(x) for x in v) + "]"
    if isinstance(v, str):
        return v
    return f"{v:.6g}"


def domain_text(domain: dict | None) -> str:
    if not domain:
        return "any"
    lo, hi = domain.get("min"), domain.get("max")
    if lo and hi:
        a = "≤" if lo["inclusive"] else "<"
        b = "≤" if hi["inclusive"] else "<"
        return f"{number(lo['value'])} {a} x {b} {number(hi['value'])}"
    if lo:
        return f"{'≥' if lo['inclusive'] else '>'} {number(lo['value'])}"
    return f"{'≤' if hi['inclusive'] else '<'} {number(hi['value'])}"


def unit_text(spec: dict) -> str:
    """The default unit, and the SI unit when it differs: `kN (SI: N)`, or `m`."""
    si = spec.get("si_unit")
    if not si:
        return "—"
    shown = spec.get("display_unit") or si
    return shown if shown == si else f"{shown} (SI: {si})"


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def input_rows(d: dict, dimension_text, condition) -> list[str]:
    rows = ["| Name | Meaning | Dimension | Unit | Required | Domain (SI) |", "|---|---|---|---|---|---|"]
    for i in d["inputs"]:
        if i.get("kind") == "choice":
            unit, dim, dom = "one of: " + ", ".join(f"`{c}`" for c in i["choices"]), "—", "—"
        else:
            dim = dimension_text(i["dimension"])
            unit = unit_text(i)
            if i.get("accepts_bearing"):
                unit += "; or `bearing`"
            dom = domain_text(i.get("domain"))
            if i.get("kind") == "list":
                dim = f"list of {dim}"
        when = condition(i)
        if i["required"]:
            req = "yes"
        elif when:
            req = f"**conditional: required when {cell(when)}**"
        else:
            req = "no" + (f" (default {number(i['default'])})" if i.get("default") is not None else "")
        rows.append(f"| `{i['name']}` | {cell(i['description'])} | {dim} | {cell(unit)} | {req} | {dom} |")
    return rows


def output_rows(d: dict, dimension_text) -> list[str]:
    rows = ["| Name | Meaning | Dimension | Unit | Shape |", "|---|---|---|---|---|"]
    for o in d["outputs"]:
        dim = dimension_text(o["dimension"])
        unit = unit_text(o)
        if o.get("kind") == "list":
            length = o["length"]
            extra = {0: "", -1: " − 1", 1: " + 1"}[length["offset"]]
            shape = f"list: one per {length['item']} (length of `{length['group']}`{extra})"
        else:
            shape = "scalar"
        rows.append(f"| `{o['name']}` | {cell(o['description'])} | {dim} | {unit} | {shape} |")
    return rows


def method_steps(trace: list[dict]) -> list[str]:
    """The formula sequence: every step once, per-item steps shown for the first item only."""
    seen, lines = set(), []
    for step in trace:
        text = step["step"]
        if "choice" in step:
            text = f"{text} = {step['choice']} (choice)"
        item = step.get("item")
        if item:
            if item["index"] != 0:
                continue
            prefix = f"{item['label']} 1: "
            text = f"for each {item['label']}: {text[len(prefix):] if text.startswith(prefix) else text}"
        if text not in seen:
            seen.add(text)
            lines.append(f"{len(lines) + 1}. `{text}`" + (f" ({step['reference']})" if step.get("reference") else ""))
    return lines


def python_call(d: dict, request: dict) -> str:
    args = []
    for name, v in request["inputs"].items():
        value = json.dumps(v["value"], ensure_ascii=False)
        args.append(f"    {name}=({value}, {json.dumps(v['unit'])})," if "unit" in v else f"    {name}={value},")
    if request.get("output_units"):
        args.append(f"    output_units={json.dumps(request['output_units'])},")
    return "\n".join([f"r = civkit.{d['id']}(", *args, ")"])


def page(d: dict, case: dict, result: dict, dimension_text, condition) -> str:
    request = case["request"]
    source = case["source"]
    lines = [
        f"# {d['title']}",
        "",
        f"> {GENERATED}",
        "",
        f"> **Disclaimer.** {DISCLAIMER}",
        "",
        f"`{d['id']}` · version {d['version']}",
        "",
        d["summary"],
        "",
        "## Inputs",
        "",
        *input_rows(d, dimension_text, condition),
    ]
    conditional = [(i["name"], condition(i)) for i in d["inputs"] if condition(i)]
    for name, when in conditional:
        lines += ["", f"> **Conditional requirement:** `{name}` is required when `{when}`."]
    for g in d.get("groups", []):
        members = ", ".join(f"`{i['name']}`" for i in d["inputs"] if i.get("group") == g["name"])
        lines += ["", f"**List group `{g['name']}`** (one entry per {g['item']}, at least {g['min_len']}): {members}. "
                      f"{g['description']}"]
    lines += ["", "## Outputs", "", *output_rows(d, dimension_text)]
    lines += ["", "## Method", "", "The steps of the calculation, in order, as its trace records them (worked example below):",
              "", *method_steps(result["trace"])]
    lines += ["", "## Validity and limits", "",
              "- Every input is checked against its mathematical domain (table above); a value outside it is an "
              "`OUT_OF_DOMAIN` error."]
    lines += [f"- {v}" for v in d.get("validity", [])]
    lines += [f"- {a}" for a in d["assumptions"] if a.startswith("Validity range:")]
    lines += ["", "## Assumptions", "", *[f"- {a}" for a in d["assumptions"] if not a.startswith("Validity range:")]]
    lines += ["", "## References", "", *[f"- {r}" for r in d["references"]]]
    lines += ["", "## Worked example", "", f"**{case['title']}**", "",
              f"Source: {source['citation']}" + ("" if source["location"] in source["citation"] else f", {source['location']}")
              + f". Licence: {source['licence']}.", "",
              "| Input | Value | Unit |", "|---|---|---|"]
    for name, v in request["inputs"].items():
        lines.append(f"| `{name}` | {cell(number(v['value']))} | {v.get('unit', '—')} |")
    lines += ["", "| Output | Source | CivKit | Unit |", "|---|---|---|---|"]
    for name, expected in case["expected"]["outputs"].items():
        got = result["outputs"][name]
        lines.append(f"| `{name}` | {number(expected['value'])} | {number(got['value'])} | {got.get('unit', '—')} |")
    lines += ["", "— in the Source column: a value the source does not give or that is not checked (see the case file).",
              f"Case file: `tests/reference/{d['id']}/{case['case']}.json`."]
    lines += ["", "## Use it", "", "Python:", "", "```python", "import civkit", "", python_call(d, request), "```", "",
              f"MCP: the tool `{d['id']}`, with each input as `{{\"value\": …, \"unit\": …}}`, or `civkit_call` with the "
              "full request. Results carry the outputs, the full trace, warnings, references and assumptions."]
    return "\n".join(lines) + "\n"


def index(descriptors: list[dict]) -> str:
    lines = ["# Calculations", "", f"> {GENERATED}", "", f"> **Disclaimer.** {DISCLAIMER}", "",
             "| Calculation | ID | Version |", "|---|---|---|"]
    for d in sorted(descriptors, key=lambda d: d["id"]):
        lines.append(f"| [{d['title']}]({d['id']}.md) | `{d['id']}` | {d['version']} |")
    return "\n".join(lines) + "\n"


def render_all() -> dict[str, str]:
    """File name → page text, for every installed calculation and the index."""
    import civkit
    from civkit._typed import condition, dimension_text

    pages = {}
    descriptors = civkit.list()
    for d in descriptors:
        case_path = ROOT / d["examples"][0]
        case = json.loads(case_path.read_text(encoding="utf-8"))
        request = case["request"]
        try:
            result = civkit.call(request["id"], version=request.get("version"), output_units=request.get("output_units"),
                                 **request["inputs"]).to_dict()
        except civkit.CivKitError as e:
            raise AssertionError(f"{case_path}: the worked example must succeed: {e}") from e
        pages[f"{d['id']}.md"] = page(d, case, result, dimension_text, condition)
    pages["README.md"] = index(descriptors)
    return pages


def main(argv: list[str]) -> int:
    pages = render_all()
    if "--check" in argv:
        stale = [n for n, t in pages.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t]
        extra = [p.name for p in OUT.glob("*.md") if p.name not in pages] if OUT.exists() else []
        for n in stale + extra:
            print(f"docs/calculations/{n} is out of date: run `python tools/gen_calc_docs.py`", file=sys.stderr)
        return 1 if stale or extra else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(pages)} pages to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
